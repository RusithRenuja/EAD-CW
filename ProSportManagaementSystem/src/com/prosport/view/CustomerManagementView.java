    private void tblCustomersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCustomersMouseClicked
        int selectedRow = tblCustomers.getSelectedRow();
    if (selectedRow != -1) {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCustomers.getModel();
        selectedCustomerId = Integer.parseInt(model.getValueAt(selectedRow, 0).toString());
        txtFullName.setText(model.getValueAt(selectedRow, 1).toString());
        txtPhone.setText(model.getValueAt(selectedRow, 2).toString());
        txtEmail.setText(model.getValueAt(selectedRow, 3).toString());
    }
    }//GEN-LAST:event_tblCustomersMouseClicked

    private void btnSaveCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveCustomerActionPerformed
        String fullName = txtFullName.getText().trim();
    String phone = txtPhone.getText().trim();
    String email = txtEmail.getText().trim();

    if (fullName.isEmpty() || phone.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Full Name and Phone Number are required!");
        return;
    }

    String sql = "INSERT INTO customers (full_name, phone, email) VALUES (?, ?, ?)";
    try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

        pstmt.setString(1, fullName);
        pstmt.setString(2, phone);
        pstmt.setString(3, email);

        if (pstmt.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Customer registered successfully!");
            loadCustomerData();
            clearCustomerForm();
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error saving customer: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSaveCustomerActionPerformed

    private void btnUpdateCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateCustomerActionPerformed
        if (selectedCustomerId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer from the table to update.");
        return;
    }

    String fullName = txtFullName.getText().trim();
    String phone = txtPhone.getText().trim();
    String email = txtEmail.getText().trim();

    String sql = "UPDATE customers SET full_name = ?, phone = ?, email = ? WHERE customer_id = ?";
    try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

        pstmt.setString(1, fullName);
        pstmt.setString(2, phone);
        pstmt.setString(3, email);
        pstmt.setInt(4, selectedCustomerId);

        if (pstmt.executeUpdate() > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Customer updated successfully!");
            loadCustomerData();
            clearCustomerForm();
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error updating customer: " + e.getMessage());
    }
    }//GEN-LAST:event_btnUpdateCustomerActionPerformed

    private void btnDeleteCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteCustomerActionPerformed
       if (selectedCustomerId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer from the table to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete this customer?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        String sql = "DELETE FROM customers WHERE customer_id = ?";
        try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, selectedCustomerId);
            if (pstmt.executeUpdate() > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Customer deleted successfully!");
                loadCustomerData();
                clearCustomerForm();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting customer: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnDeleteCustomerActionPerformed

