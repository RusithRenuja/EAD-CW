    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCart.getModel();
    if (model.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Cart is empty. Add items before processing checkout.");
        return;
    }

    try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection()) {
        conn.setAutoCommit(false); // Begin SQL transaction block

        // 1. Calculate Total Amount
        String totalText = lblTotalAmount.getText().replaceAll("[^0-9.]", "");
        double totalAmount = Double.parseDouble(totalText);

        // 2. Insert Record into Sales Table
        java.sql.PreparedStatement stmtSale = conn.prepareStatement(
            "INSERT INTO sales (total_amount) VALUES (?)",
            java.sql.Statement.RETURN_GENERATED_KEYS
        );
        stmtSale.setDouble(1, totalAmount);
        stmtSale.executeUpdate();

        // 3. Update Inventory Stock for Each Item
        java.sql.PreparedStatement stmtStock = conn.prepareStatement(
            "UPDATE products SET stock_quantity = stock_quantity - ? WHERE product_id = ?"
        );

        for (int i = 0; i < model.getRowCount(); i++) {
            int productId = Integer.parseInt(model.getValueAt(i, 0).toString());
            int qty = Integer.parseInt(model.getValueAt(i, 3).toString());

            stmtStock.setInt(1, qty);
            stmtStock.setInt(2, productId);
            stmtStock.addBatch();
        }
        stmtStock.executeBatch();

        conn.commit(); // Commit database transaction
        conn.setAutoCommit(true);

        javax.swing.JOptionPane.showMessageDialog(this, "Transaction completed successfully!");

        // Reset cart table
        model.setRowCount(0);
        calculateTotal();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Checkout Failed: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

