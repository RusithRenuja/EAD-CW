    public void loadCustomerData() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCustomers.getModel();
    model.setRowCount(0);
    try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
         java.sql.Statement stmt = conn.createStatement();
         java.sql.ResultSet rs = stmt.executeQuery("SELECT * FROM customers")) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("customer_id"),
                rs.getString("full_name"),
                rs.getString("phone"),
                rs.getString("email")
            });
        }
    } catch (Exception e) {
        // Table loads empty if no records exist
    }
}
    
