    private void loadCustomers() {
    try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
         java.sql.Statement stmt = conn.createStatement();
         java.sql.ResultSet rs = stmt.executeQuery("SELECT full_name FROM customers")) {
        
        cmbCustomers.removeAllItems();
        cmbCustomers.addItem("-- Select Customer --");
        while (rs.next()) {
            cmbCustomers.addItem(rs.getString("full_name"));
        }
    } catch (Exception e) {
        // If table doesn't exist yet, keep default items
    }
}
    
    private void calculateTotal() {
    double total = 0.0;
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCart.getModel();
    for (int i = 0; i < model.getRowCount(); i++) {
        double subtotal = Double.parseDouble(model.getValueAt(i, 4).toString());
        total += subtotal;
    }
    lblTotalAmount.setText(String.format("Total: %.2f", total));
}

