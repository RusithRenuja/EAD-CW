    public void loadProductData() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProducts.getModel();
    model.setRowCount(0);
    try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
         java.sql.Statement stmt = conn.createStatement();
         java.sql.ResultSet rs = stmt.executeQuery("SELECT * FROM products")) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("product_id"),
                rs.getString("barcode"),
                rs.getString("product_name"),
                rs.getString("category"),
                rs.getDouble("unit_price"),
                rs.getInt("stock_quantity")
            });
        }
    } catch (Exception e) {
        // Table loads empty if no records exist
    }
}
    
