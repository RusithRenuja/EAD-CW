    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        String barcode = txtSearchBarcode.getText().trim();
    String qtyStr = txtQuantity.getText().trim();

    if (barcode.isEmpty() || qtyStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter Barcode and Quantity.");
        return;
    }

    try {
        int requestedQty = Integer.parseInt(qtyStr);
        if (requestedQty <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Quantity must be greater than 0.");
            return;
        }

        java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
        java.sql.PreparedStatement pstmt = conn.prepareStatement("SELECT * FROM products WHERE barcode = ?");
        pstmt.setString(1, barcode);
        java.sql.ResultSet rs = pstmt.executeQuery();

        if (rs.next()) {
            int productId = rs.getInt("product_id");
            String productName = rs.getString("product_name");
            double unitPrice = rs.getDouble("unit_price");
            int stock = rs.getInt("stock_quantity");

            if (requestedQty > stock) {
                javax.swing.JOptionPane.showMessageDialog(this, "Insufficient stock! Available in database: " + stock);
                return;
            }

            double subtotal = unitPrice * requestedQty;

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCart.getModel();
            model.addRow(new Object[]{productId, productName, unitPrice, requestedQty, subtotal});

            calculateTotal();
            txtSearchBarcode.setText("");
            txtQuantity.setText("1");
            txtSearchBarcode.requestFocus();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Product not found for Barcode: " + barcode);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid numeric quantity.");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error adding item: " + e.getMessage());
    }
    }//GEN-LAST:event_btnAddToCartActionPerformed

    private void btnRemoveItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveItemActionPerformed
        int selectedRow = tblCart.getSelectedRow();
    if (selectedRow != -1) {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCart.getModel();
        model.removeRow(selectedRow);
        calculateTotal();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an item from the cart table to remove.");
    }
    }//GEN-LAST:event_btnRemoveItemActionPerformed

