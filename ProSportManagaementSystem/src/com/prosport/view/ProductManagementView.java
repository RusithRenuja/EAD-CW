    private void tblProductsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductsMouseClicked
        int selectedRow = tblProducts.getSelectedRow();
        if (selectedRow != -1) {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProducts.getModel();
        selectedProductId = Integer.parseInt(model.getValueAt(selectedRow, 0).toString());
        txtBarcode.setText(model.getValueAt(selectedRow, 1).toString());
        txtProductName.setText(model.getValueAt(selectedRow, 2).toString());
        cmbCategory.setSelectedItem(model.getValueAt(selectedRow, 3).toString());
        txtUnitPrice.setText(model.getValueAt(selectedRow, 4).toString());
        txtQuantity.setText(model.getValueAt(selectedRow, 5).toString());
    }
    }//GEN-LAST:event_tblProductsMouseClicked

    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed
       String barcode = txtBarcode.getText().trim();
    String name = txtProductName.getText().trim();
    String category = cmbCategory.getSelectedItem() != null ? cmbCategory.getSelectedItem().toString() : "";
    String priceStr = txtUnitPrice.getText().trim();
    String stockStr = txtQuantity.getText().trim();

    if (barcode.isEmpty() || name.isEmpty() || priceStr.isEmpty() || stockStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    try {
        double price = Double.parseDouble(priceStr);
        int stock = Integer.parseInt(stockStr);

        String sql = "INSERT INTO products (barcode, product_name, category, unit_price, stock_quantity) VALUES (?, ?, ?, ?, ?)";
        try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, barcode);
            pstmt.setString(2, name);
            pstmt.setString(3, category);
            pstmt.setDouble(4, price);
            pstmt.setInt(5, stock);

            if (pstmt.executeUpdate() > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Product added successfully!");
                loadProductData();
                clearProductForm();
            }
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Price and Stock must be valid numeric values.");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error adding product: " + e.getMessage());
    }
    }//GEN-LAST:event_btnAddProductActionPerformed

    private void btnUpdateProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateProductActionPerformed
        if (selectedProductId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a product from the table to update.");
        return;
    }

    String barcode = txtBarcode.getText().trim();
    String name = txtProductName.getText().trim();
    String category = cmbCategory.getSelectedItem() != null ? cmbCategory.getSelectedItem().toString() : "";
    String priceStr = txtUnitPrice.getText().trim();
    String stockStr = txtQuantity.getText().trim();

    try {
        double price = Double.parseDouble(priceStr);
        int stock = Integer.parseInt(stockStr);

        String sql = "UPDATE products SET barcode = ?, product_name = ?, category = ?, unit_price = ?, stock_quantity = ? WHERE product_id = ?";
        try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, barcode);
            pstmt.setString(2, name);
            pstmt.setString(3, category);
            pstmt.setDouble(4, price);
            pstmt.setInt(5, stock);
            pstmt.setInt(6, selectedProductId);

            if (pstmt.executeUpdate() > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Product updated successfully!");
                loadProductData();
                clearProductForm();
            }
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Price and Stock must be valid numeric values.");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error updating product: " + e.getMessage());
    }
    }//GEN-LAST:event_btnUpdateProductActionPerformed

    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
        if (selectedProductId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a product from the table to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete this product?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        String sql = "DELETE FROM products WHERE product_id = ?";
        try (java.sql.Connection conn = com.prosport.config.DBConnection.getInstance().getConnection();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, selectedProductId);
            if (pstmt.executeUpdate() > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Product deleted successfully!");
                loadProductData();
                clearProductForm();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting product: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnDeleteProductActionPerformed

